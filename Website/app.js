const supportedLocales = Object.keys(copy);
const localeAliases = {
  "zh": "zh-Hans",
  "zh-cn": "zh-Hans",
  "zh-sg": "zh-Hans",
  "zh-hans": "zh-Hans",
  "zh-tw": "zh-Hant",
  "zh-hk": "zh-Hant",
  "zh-mo": "zh-Hant",
  "zh-hant": "zh-Hant"
};
const storeBadgeLocales = {
  ko: "ko-kr",
  en: "en-us",
  "zh-Hans": "zh-cn",
  "zh-Hant": "zh-tw",
  ja: "ja-jp"
};

function normalizeLocale(value) {
  if (!value) return null;
  if (supportedLocales.includes(value)) return value;
  const lower = value.toLowerCase();
  if (localeAliases[lower]) return localeAliases[lower];
  const base = lower.split("-")[0];
  return supportedLocales.find((locale) => locale.toLowerCase() === base) || null;
}

function preferredLocale() {
  const params = new URLSearchParams(window.location.search);
  const fromURL = normalizeLocale(params.get("lang"));
  if (fromURL) return fromURL;

  const stored = normalizeLocale(window.localStorage.getItem("nudgemate-language"));
  if (stored) return stored;

  for (const language of navigator.languages || [navigator.language]) {
    const normalized = normalizeLocale(language);
    if (normalized) return normalized;
  }
  return "en";
}

function applyLocale(locale, updateURL = false) {
  const strings = copy[locale] || copy.en;
  document.documentElement.lang = locale;
  document.title = strings.metaTitle;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (strings[key]) element.textContent = strings[key];
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const key = element.dataset.i18nAlt;
    if (strings[key]) element.alt = strings[key];
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const key = element.dataset.i18nAriaLabel;
    if (strings[key]) element.setAttribute("aria-label", strings[key]);
  });

  const badgeLocale = storeBadgeLocales[locale] || storeBadgeLocales.en;
  document.querySelectorAll("[data-store-badge]").forEach((storeBadge) => {
    storeBadge.src = `https://tools.applemediaservices.com/api/badges/download-on-the-app-store/black/${badgeLocale}`;
  });

  document.querySelector('meta[name="description"]')?.setAttribute("content", strings.metaDescription);
  document.querySelector('meta[property="og:title"]')?.setAttribute("content", strings.metaTitle);
  document.querySelector('meta[property="og:description"]')?.setAttribute("content", strings.metaDescription);
  document.querySelector('meta[name="twitter:title"]')?.setAttribute("content", strings.metaTitle);
  document.querySelector('meta[name="twitter:description"]')?.setAttribute("content", strings.metaDescription);

  const selector = document.querySelector("#language");
  if (selector) {
    selector.value = locale;
    selector.setAttribute("aria-label", strings.languageLabel);
  }

  window.localStorage.setItem("nudgemate-language", locale);
  if (updateURL) {
    const url = new URL(window.location.href);
    url.searchParams.set("lang", locale);
    window.history.replaceState({}, "", url);
  }
}

applyLocale(preferredLocale());

document.querySelector("#language")?.addEventListener("change", (event) => {
  applyLocale(event.target.value, true);
});

const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
const revealElements = document.querySelectorAll(".reveal");

if (reduceMotion || !("IntersectionObserver" in window)) {
  revealElements.forEach((element) => element.classList.add("is-visible"));
} else {
  const revealObserver = new IntersectionObserver((entries, observer) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add("is-visible");
      observer.unobserve(entry.target);
    });
  }, { threshold: 0.13, rootMargin: "0px 0px -7%" });
  revealElements.forEach((element) => revealObserver.observe(element));
}

const device = document.querySelector("[data-device]");
const chapters = document.querySelectorAll("[data-scene]");
if (device && "IntersectionObserver" in window) {
  const sceneObserver = new IntersectionObserver((entries) => {
    const visible = entries
      .filter((entry) => entry.isIntersecting)
      .sort((a, b) => b.intersectionRatio - a.intersectionRatio)[0];
    if (visible) device.dataset.activeScene = visible.target.dataset.scene;
  }, { threshold: [0.3, 0.5, 0.7], rootMargin: "-20% 0px -35%" });
  chapters.forEach((chapter) => sceneObserver.observe(chapter));
}

const header = document.querySelector("[data-header]");
const progress = document.querySelector(".scroll-progress span");
const heroArt = document.querySelector("[data-hero-art]");
let ticking = false;

function updateScrollEffects() {
  const y = window.scrollY;
  const max = Math.max(1, document.documentElement.scrollHeight - window.innerHeight);
  document.documentElement.style.setProperty("--scroll-progress", `${Math.min(1, y / max)}`);
  if (progress) progress.style.transform = `scaleX(${Math.min(1, y / max)})`;
  header?.classList.toggle("is-scrolled", y > 20);

  if (!reduceMotion && heroArt && y < window.innerHeight * 1.3) {
    const travel = Math.min(1, y / window.innerHeight);
    heroArt.style.setProperty("--hero-shift", `${travel * 42}px`);
    heroArt.style.setProperty("--hero-scale", `${1 + travel * 0.035}`);
  }
  ticking = false;
}

window.addEventListener("scroll", () => {
  if (ticking) return;
  ticking = true;
  window.requestAnimationFrame(updateScrollEffects);
}, { passive: true });
updateScrollEffects();

